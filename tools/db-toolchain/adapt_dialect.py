# -*- coding: utf-8 -*-
"""把 dbdiagram.io 导出的通用 DDL 适配成目标数据库可直接执行的建表脚本。

为什么需要这一步
    dbdiagram.io 的 Oracle / PostgreSQL 导出保留 DBML 的通用类型
    （bigint、varchar、text、GENERATED AS IDENTITY ...），这些不是目标库的原生语法，
    直接执行会报错。本脚本把适配规则固化下来，保证「建模工具导出 → 物理建表」可复现。

适配规则
    --target oracle   （输入：dbml_export_oracle.sql）
        bigint                    -> NUMBER(19)
        int                       -> NUMBER(10)
        varchar(n)                -> VARCHAR2(n)
        decimal(p,s)              -> NUMBER(p,s)
        text                      -> CLOB
        GENERATED AS IDENTITY     -> GENERATED BY DEFAULT AS IDENTITY

    --target h2       （输入：dbml_export_postgres.sql）
        删除 Oracle/PostgreSQL 专有的 DEFERRABLE INITIALLY IMMEDIATE（H2 不支持）

产出
    docs/database/sql/schema-dbml-oracle.sql                     供文档与评审使用
    backend/src/main/resources/db/schema-dbml-oracle.sql         应用启动时 OracleSchemaBootstrapRunner 执行
    docs/database/sql/schema-dbml-h2.sql                         离线回退用
    backend/src/main/resources/db/schema-dbml-h2.sql             SchemaBootstrapRunner 执行

运行
    cd tools/db-toolchain
    python adapt_dialect.py --target oracle
    python adapt_dialect.py --target h2

    也可以自定义输入输出：
    python adapt_dialect.py --target oracle --input my_export.sql --output my_schema.sql --no-backend
"""
import argparse
import io
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

# --- 路径约定 ---------------------------------------------------------------
# 本文件位于 <repo>/tools/db-toolchain/，向上两级就是仓库根目录。
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
DOCS_SQL = os.path.join(REPO, "docs", "database", "sql")
EXPORT_DIR = os.path.join(DOCS_SQL, "dbdiagram-export")
BACKEND_DB = os.path.join(REPO, "backend", "src", "main", "resources", "db")

# --- 适配规则 ---------------------------------------------------------------
ORACLE_RULES = [
    # 顺序有讲究：先替换带精度/长度的类型，再替换裸类型，避免互相干扰。
    (r"\bvarchar\((\d+)\)", r"VARCHAR2(\1)", "varchar(n) -> VARCHAR2(n)"),
    (r"\bdecimal\((\d+)\s*,\s*(\d+)\)", r"NUMBER(\1,\2)", "decimal(p,s) -> NUMBER(p,s)"),
    (r"\bbigint\b", "NUMBER(19)", "bigint -> NUMBER(19)"),
    (r"\bint\b", "NUMBER(10)", "int -> NUMBER(10)"),
    (r"\btext\b", "CLOB", "text -> CLOB"),
    (r"GENERATED\s+AS\s+IDENTITY", "GENERATED BY DEFAULT AS IDENTITY",
     "GENERATED AS IDENTITY -> GENERATED BY DEFAULT AS IDENTITY"),
]

H2_RULES = [
    (r"\s+DEFERRABLE\s+INITIALLY\s+IMMEDIATE", "", "删除 DEFERRABLE INITIALLY IMMEDIATE"),
]


def adapt(text, rules):
    """按规则依次替换，返回（结果文本, 每条规则命中次数）。"""
    counts = []
    for pattern, repl, label in rules:
        text, n = re.subn(pattern, repl, text)
        counts.append((label, n))
    return text, counts


def summarize(text):
    return {
        "create_table": len(re.findall(r"\bCREATE\s+TABLE\b", text, re.I)),
        "foreign_key": len(re.findall(r"\bADD\s+FOREIGN\s+KEY\b", text, re.I)),
        "identity": len(re.findall(r"\bIDENTITY\b", text, re.I)),
    }


def write_outputs(text, target, output, also_backend):
    os.makedirs(os.path.dirname(output), exist_ok=True)
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"[ok] {output}")

    if also_backend:
        backend_path = os.path.join(BACKEND_DB, os.path.basename(output))
        os.makedirs(BACKEND_DB, exist_ok=True)
        with open(backend_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"[ok] {backend_path}")


def main():
    parser = argparse.ArgumentParser(description="dbdiagram.io DDL 方言适配")
    parser.add_argument("--target", required=True, choices=["oracle", "h2"],
                        help="目标数据库方言")
    parser.add_argument("--input", help="dbdiagram.io 导出的 DDL（默认取 dbdiagram-export 下对应文件）")
    parser.add_argument("--output", help="输出路径（默认 docs/database/sql/schema-dbml-<target>.sql）")
    parser.add_argument("--no-backend", action="store_true",
                        help="只写 docs，不同步到 backend/src/main/resources/db/")
    args = parser.parse_args()

    if args.target == "oracle":
        default_input = os.path.join(EXPORT_DIR, "dbml_export_oracle.sql")
        default_output = os.path.join(DOCS_SQL, "schema-dbml-oracle.sql")
        rules = ORACLE_RULES
    else:
        default_input = os.path.join(EXPORT_DIR, "dbml_export_postgres.sql")
        default_output = os.path.join(DOCS_SQL, "schema-dbml-h2.sql")
        rules = H2_RULES

    src = args.input or default_input
    dst = args.output or default_output
    if not os.path.exists(src):
        raise SystemExit(f"找不到输入文件：{src}\n请先用 dbdiagram.io 或 @dbml/cli 导出 DDL。")

    with open(src, encoding="utf-8") as f:
        text = f.read()

    print(f"输入：{src}")
    text, counts = adapt(text, rules)
    for label, n in counts:
        print(f"  替换 {label}：{n} 处")
    stats = summarize(text)
    print(f"  结果：{stats['create_table']} 张表 / {stats['foreign_key']} 个外键 / {stats['identity']} 个身份列")

    write_outputs(text, args.target, dst, not args.no_backend)


if __name__ == "__main__":
    main()