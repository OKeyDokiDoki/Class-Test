CREATE TABLE app_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_code VARCHAR(64) NOT NULL,
  role_code VARCHAR(20) NOT NULL DEFAULT 'RESIDENT',
  nickname VARCHAR(50),
  phone_hash VARCHAR(64),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  last_login_at TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_app_user PRIMARY KEY (id),
  CONSTRAINT uk_app_user_user_code UNIQUE (user_code),
  CONSTRAINT uk_app_user_phone_hash UNIQUE (phone_hash),
  CONSTRAINT ck_app_user_role_code CHECK (role_code IN ('RESIDENT','MERCHANT','COMMUNITY','ADMIN')),
  CONSTRAINT ck_app_user_status CHECK (status IN ('ACTIVE','DISABLED','DELETED'))
);
CREATE INDEX idx_app_user_role_status ON app_user (role_code, status);

CREATE TABLE user_profile (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_id BIGINT NOT NULL,
  profile_type VARCHAR(20) NOT NULL,
  profile_label VARCHAR(50) NOT NULL,
  source VARCHAR(20) NOT NULL DEFAULT 'FORM',
