COMMENT ON COLUMN road_segment.from_node_id IS '起点节点';
COMMENT ON COLUMN road_segment.to_node_id IS '终点节点';
COMMENT ON COLUMN road_segment.road_name IS '道路名称';
COMMENT ON COLUMN road_segment.road_level IS '道路等级';
COMMENT ON COLUMN road_segment.length_m IS '路段长度；米';
COMMENT ON COLUMN road_segment.walk_time_s IS '步行耗时；秒，按 1.2 m/s 及过街等待估算';
COMMENT ON COLUMN road_segment.is_walkable IS '是否可步行';
COMMENT ON COLUMN road_segment.updated_at IS '更新时间';
