CREATE TABLE road_segment (
    id                         NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
    segment_code               VARCHAR2(50)     NOT NULL,
    district_id                NUMBER(19),
    from_node_id               NUMBER(19)       NOT NULL,
    to_node_id                 NUMBER(19)       NOT NULL,
    road_name                  VARCHAR2(100),
    road_level                 VARCHAR2(20)     DEFAULT 'BRANCH' NOT NULL,
    length_m                   NUMBER(10,2)     NOT NULL,
    walk_time_s                NUMBER(10)       NOT NULL,
    is_walkable                CHAR(1)          DEFAULT 'Y' NOT NULL,
    updated_at                 TIMESTAMP(6)     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_road_segment PRIMARY KEY (id),
    CONSTRAINT uk_road_segment_segment_code UNIQUE (segment_code),
    CONSTRAINT ck_road_segment_road_level CHECK (road_level IN ('MAIN','BRANCH','ALLEY')),
    CONSTRAINT ck_road_segment_length_m CHECK (length_m > 0),
    CONSTRAINT ck_road_segment_walk_time_s CHECK (walk_time_s > 0),
    CONSTRAINT ck_road_segment_is_walkable CHECK (is_walkable IN ('Y','N')),
    CONSTRAINT fk_road_segment_district_id FOREIGN KEY (district_id) REFERENCES district (id) ON DELETE SET NULL,
    CONSTRAINT fk_road_segment_from_node_id FOREIGN KEY (from_node_id) REFERENCES road_node (id),
    CONSTRAINT fk_road_segment_to_node_id FOREIGN KEY (to_node_id) REFERENCES road_node (id)
