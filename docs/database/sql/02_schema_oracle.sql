CREATE TABLE district (
    id                         NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
    district_code              VARCHAR2(40)     NOT NULL,
    district_name              VARCHAR2(100)    NOT NULL,
    parent_id                  NUMBER(19),
    district_level             VARCHAR2(20)     NOT NULL,
    city_code                  VARCHAR2(20)     NOT NULL,
    center_lng                 NUMBER(10,6),
    center_lat                 NUMBER(10,6),
    boundary_geojson           CLOB,
    area_sqm                   NUMBER(12,2),
    resident_count             NUMBER(10),
    status                     VARCHAR2(20)     DEFAULT 'ACTIVE' NOT NULL,
    created_at                 TIMESTAMP(6)     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at                 TIMESTAMP(6)     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_district PRIMARY KEY (id),
    CONSTRAINT uk_district_district_code UNIQUE (district_code),
    CONSTRAINT ck_district_district_level CHECK (district_level IN ('STREET','COMMUNITY','GRID')),
    CONSTRAINT ck_district_center_lng CHECK (center_lng BETWEEN -180 AND 180),
    CONSTRAINT ck_district_center_lat CHECK (center_lat BETWEEN -90 AND 90),
    CONSTRAINT ck_district_resident_count CHECK (resident_count >= 0),
    CONSTRAINT ck_district_status CHECK (status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT fk_district_parent_id FOREIGN KEY (parent_id) REFERENCES district (id)
)
  LOB (boundary_geojson) STORE AS SECUREFILE (TABLESPACE TBS_LIFECIRCLE_LOB COMPRESS HIGH)
  TABLESPACE TBS_LIFECIRCLE_DATA;
COMMENT ON TABLE district IS '社区片区表：街道—社区—网格三级空间主数据，是设施、评估、选址和治理的公共维度。';
COMMENT ON COLUMN district.id IS '主键';
COMMENT ON COLUMN district.district_code IS '片区编码；行政区划码+序号，全局唯一';
COMMENT ON COLUMN district.district_name IS '片区名称';
COMMENT ON COLUMN district.parent_id IS '上级片区；自关联，街道→社区→网格';
COMMENT ON COLUMN district.district_level IS '层级；STREET/COMMUNITY/GRID';
COMMENT ON COLUMN district.city_code IS '城市行政区划代码；GB/T 2260 六位代码';
COMMENT ON COLUMN district.center_lng IS '中心点经度；WGS84，单位度';
COMMENT ON COLUMN district.center_lat IS '中心点纬度；WGS84，单位度';
COMMENT ON COLUMN district.boundary_geojson IS '边界 GeoJSON；片区边界，GeoJSON Polygon';
COMMENT ON COLUMN district.area_sqm IS '面积；平方米';
COMMENT ON COLUMN district.resident_count IS '常住人口；人';
COMMENT ON COLUMN district.status IS '状态';
COMMENT ON COLUMN district.created_at IS '创建时间';
COMMENT ON COLUMN district.updated_at IS '更新时间';
CREATE INDEX idx_district_parent ON district (parent_id) TABLESPACE TBS_LIFECIRCLE_IDX;
CREATE INDEX idx_district_city ON district (city_code, district_level) TABLESPACE TBS_LIFECIRCLE_IDX;

