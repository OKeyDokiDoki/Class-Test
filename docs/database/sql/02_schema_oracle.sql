SET DEFINE OFF;

CREATE TABLE app_user (
    id                         NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
    user_code                  VARCHAR2(64)     NOT NULL,
    role_code                  VARCHAR2(20)     DEFAULT 'RESIDENT' NOT NULL,
    nickname                   VARCHAR2(50),
    phone_hash                 VARCHAR2(64),
    status                     VARCHAR2(20)     DEFAULT 'ACTIVE' NOT NULL,
    last_login_at              TIMESTAMP(6),
    created_at                 TIMESTAMP(6)     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at                 TIMESTAMP(6)     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (id),
    CONSTRAINT uk_app_user_user_code UNIQUE (user_code),
    CONSTRAINT uk_app_user_phone_hash UNIQUE (phone_hash),
    CONSTRAINT ck_app_user_role_code CHECK (role_code IN ('RESIDENT','MERCHANT','COMMUNITY','ADMIN')),
    CONSTRAINT ck_app_user_status CHECK (status IN ('ACTIVE','DISABLED','DELETED'))
)
  TABLESPACE TBS_LIFECIRCLE_DATA;
COMMENT ON TABLE app_user IS '用户账号表：三类使用者的统一账号，只保存脱敏业务编号与手机号哈希，不落库明文手机号。';
COMMENT ON COLUMN app_user.id IS '主键；自增主键';
COMMENT ON COLUMN app_user.user_code IS '用户业务编号；脱敏编号，居民 R、商户 M、社区 C 前缀';
COMMENT ON COLUMN app_user.role_code IS '角色编码；RESIDENT 居民 / MERCHANT 商户 / COMMUNITY 社区 / ADMIN 管理员';
COMMENT ON COLUMN app_user.nickname IS '昵称；展示名称，可为空';
COMMENT ON COLUMN app_user.phone_hash IS '手机号哈希；SHA-256 加盐哈希，用于登录匹配，不可逆';
COMMENT ON COLUMN app_user.status IS '账号状态；ACTIVE/DISABLED/DELETED';
COMMENT ON COLUMN app_user.last_login_at IS '最近登录时间；UTC 时间';
COMMENT ON COLUMN app_user.created_at IS '创建时间';
COMMENT ON COLUMN app_user.updated_at IS '更新时间';
CREATE INDEX idx_app_user_role_status ON app_user (role_code, status) TABLESPACE TBS_LIFECIRCLE_IDX;

CREATE TABLE user_profile (
    id                         NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
    user_id                    NUMBER(19)       NOT NULL,
    profile_type               VARCHAR2(20)     NOT NULL,
    profile_label              VARCHAR2(50)     NOT NULL,
    source                     VARCHAR2(20)     DEFAULT 'FORM' NOT NULL,
    confidence                 NUMBER(5,2),
    version_no                 NUMBER(10)       DEFAULT 1 NOT NULL,
    is_current                 CHAR(1)          DEFAULT 'Y' NOT NULL,
    created_at                 TIMESTAMP(6)     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_user_profile PRIMARY KEY (id),
    CONSTRAINT uk_user_profile_ver UNIQUE (user_id, version_no),
    CONSTRAINT ck_user_profile_profile_type CHECK (profile_type IN ('RESIDENT','MERCHANT')),
    CONSTRAINT ck_user_profile_source CHECK (source IN ('FORM','CHAT','IMPORT')),
    CONSTRAINT ck_user_profile_confidence CHECK (confidence BETWEEN 0 AND 100),
    CONSTRAINT ck_user_profile_is_current CHECK (is_current IN ('Y','N')),
    CONSTRAINT fk_user_profile_user_id FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
