  TABLESPACE TBS_LIFECIRCLE_DATA;
COMMENT ON TABLE user_profile IS '用户画像表：一次画像生成的版本化结果，保留历史版本，is_current 标记当前生效画像。';
COMMENT ON COLUMN user_profile.id IS '主键';
COMMENT ON COLUMN user_profile.user_id IS '用户；所属用户';
COMMENT ON COLUMN user_profile.profile_type IS '画像类型；居民画像或商户画像';
COMMENT ON COLUMN user_profile.profile_label IS '画像标签；如“青年夜班画像”“稳健型商户画像”';
COMMENT ON COLUMN user_profile.source IS '生成方式；表单/多轮对话/导入';
COMMENT ON COLUMN user_profile.confidence IS '画像置信度；0-100，表示标签可信程度';
COMMENT ON COLUMN user_profile.version_no IS '版本号；从 1 递增';
COMMENT ON COLUMN user_profile.is_current IS '是否当前版本；Y/N，同一用户仅一条 Y';
COMMENT ON COLUMN user_profile.created_at IS '创建时间';
CREATE INDEX idx_user_profile_cur ON user_profile (user_id, is_current) TABLESPACE TBS_LIFECIRCLE_IDX;

